const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const resolve = Module._resolveFilename;
Module._resolveFilename = function(request, ...args) { return resolve.call(this, request.startsWith('@/') ? path.join(root, request.slice(2)) : request, ...args); };
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,esModuleInterop:true}}).outputText, filename);
const { checkDiagramLabels, respiratoryLabels, digestiveLabels } = require('../lib/diagramLabels.ts');
assert.deepEqual(checkDiagramLabels(['mouth', 'ESOPHAGUS', 'liver', 'stomach', 'small intestine', 'colon'], digestiveLabels), Array(6).fill(true));
assert.deepEqual(checkDiagramLabels(['', 'food pipe', 'stomach', 'liver', 'large intestine', 'small intestine'], digestiveLabels), Array(6).fill(false));
assert.deepEqual(checkDiagramLabels([' Windpipe ', 'LUNGS', 'bronchus', 'bronchiole', 'air sacs', 'diaphragm']), Array(6).fill(true));
assert.deepEqual(checkDiagramLabels(['t', 'heart', '', 'bronchi', 'alve', 'ribs']), Array(6).fill(false));
assert.deepEqual(checkDiagramLabels([]), Array(6).fill(false));
const store = new Map();
global.window = {localStorage:{getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v)}};
const { recordQuizResult, loadProgress } = require('../lib/progress.ts');
const answers = respiratoryLabels.map(label => ({questionId:label.name,sourceId:`respiratory-label-${label.name.toLowerCase()}`,topic:'Year 8 Organisms',subtopic:'Gas exchange',correct:true,userAnswer:label.name}));
const result = {score:6,total:6,answers};
recordQuizResult(result);
assert.equal(loadProgress().questionsAnswered,6);
